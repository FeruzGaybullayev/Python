# Data Type - Ma'lumot toifasi

# Primitive Data Types - Oddiy ma'lumot turlari

# Numbers - raqamlar
print(type(1)) # int - Integer - Butun son
print(type(2)) # int - Integer - Butun son
print(type(1.5)) # Float - Float - Haqiqiy son
print(type(2+3j)) # complex - Complex - Kompleks son

# Strings - matnlar
print(type("Hello")) # str - String - so'z
print(type('True')) # str -String - so'z

# Boolean - mantiqiy qiymat
print(type(True)) # bool - Boolean - mantiqiy qiymat
print(type(False)) # bool - Boolean - mantiqiy qiymat

